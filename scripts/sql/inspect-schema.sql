-- Read-only. Aggregates only — do not SELECT user/realm rows.
-- Requires MYSQL_HOST / MYSQL_USER / MYSQL_PWD / MYSQL_DATABASE (or run inside that schema).

SELECT SCHEMA_NAME, DEFAULT_CHARACTER_SET_NAME, DEFAULT_COLLATION_NAME
FROM information_schema.SCHEMATA
WHERE SCHEMA_NAME = DATABASE();

SELECT TABLE_COLLATION, COUNT(*) AS tables
FROM information_schema.TABLES
WHERE TABLE_SCHEMA = DATABASE()
  AND TABLE_TYPE = 'BASE TABLE'
GROUP BY TABLE_COLLATION
ORDER BY tables DESC;

SELECT COLUMN_NAME, CHARACTER_SET_NAME, COLLATION_NAME
FROM information_schema.COLUMNS
WHERE TABLE_SCHEMA = DATABASE()
  AND TABLE_NAME = 'KEYCLOAK_GROUP'
  AND COLUMN_NAME = 'ORG_ID';

SELECT TABLE_NAME
FROM information_schema.TABLES
WHERE TABLE_SCHEMA = DATABASE()
  AND TABLE_NAME = 'USER_VER_CREDENTIAL';

SELECT ID, AUTHOR, FILENAME, DATEEXECUTED, EXECTYPE
FROM DATABASECHANGELOG
WHERE ID LIKE '26.6.0%'
   OR ID LIKE '26.7.0%'
ORDER BY DATEEXECUTED, ID;
